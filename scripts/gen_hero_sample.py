#!/usr/bin/env python3
"""Generates frontend/src/landing/heroSample.ts from the real rule-based engine output on the critical example."""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.examples import EXAMPLES
from app.service import ReviewService
from app.store import Store
OUTPUT_FILE = ROOT / "frontend" / "src" / "landing" / "heroSample.ts"


def generate_hero_sample_data():
    crit = next(e for e in EXAMPLES if e["id"] == "critical")
    svc = ReviewService(Store(":memory:"))
    rev = svc.review(crit["claim"], crit["evidence"])

    comparisons_data = [c.model_dump() for c in rev.comparisons]
    language_risks_data = [r.model_dump() for r in rev.language_risks]

    return {
        "claim_text": rev.claim_text,
        "evidence_text": rev.evidence_text,
        "verdict_status": rev.verdict.status.value,
        "verdict_title": "Not supported by the evidence",
        "comparisons": comparisons_data,
        "language_risks": language_risks_data,
    }


def render_ts(data: dict) -> str:
    content = json.dumps(data, indent=2)
    return f"""// Auto-generated by scripts/gen_hero_sample.py. Do not edit directly.
import type {{ Comparison, LanguageRisk, VerdictStatus }} from "../types";

export interface HeroSample {{
  claim_text: string;
  evidence_text: string;
  verdict_status: VerdictStatus;
  verdict_title: string;
  comparisons: Comparison[];
  language_risks: LanguageRisk[];
}}

export const HERO_SAMPLE: HeroSample = {content};
"""


def main():
    data = generate_hero_sample_data()
    ts_code = render_ts(data)
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(ts_code, encoding="utf-8")
    print(f"Generated {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
