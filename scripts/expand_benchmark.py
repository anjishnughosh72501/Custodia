def main():
    cases_file = Path("bench/cases.jsonl")
    existing_ids = set()
    cases = []
    if cases_file.exists():
        with open(cases_file, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    c = json.loads(line)
                    existing_ids.add(c["id"])
                    cases.append(c)

    added = 0
    for nc in NEW_CASES:
        if nc["id"] not in existing_ids:
            cases.append(nc)
            existing_ids.add(nc["id"])
            added += 1

    with open(cases_file, "w", encoding="utf-8") as f:
        for c in cases:
            f.write(json.dumps(c) + "\n")

    print(f"Benchmark expanded: {len(cases)} total cases ({added} newly added).")

